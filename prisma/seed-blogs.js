async function main() {
  console.log('🌱 Seeding blog articles into database...');

  // Find or create default organization
  let org = await prisma.organization.findFirst();
  if (!org) {
    org = await prisma.organization.create({
      data: {
        name: 'OneClickBiz Official',
        slug: 'oneclickbiz',
        subscriptionStatus: 'active'
      }
    });
    console.log(`Created default organization: ${org.name} (${org.id})`);
  }

  for (const post of SAMPLE_POSTS) {
    const existing = await prisma.blogPost.findUnique({
      where: { slug: post.slug }
    });

    if (existing) {
      await prisma.blogPost.update({
        where: { slug: post.slug },
        data: {
          title: post.title,
          excerpt: post.excerpt,
          content: post.content,
          coverImage: post.coverImage,
          category: post.category,
          readTimeMinutes: post.readTimeMinutes,
          authorName: post.authorName,
          tags: post.tags,
          isPublished: true,
          viewsCount: post.viewsCount
        }
      });
      console.log(`Updated post: ${post.title}`);
    } else {
      await prisma.blogPost.create({
        data: {
          organizationId: org.id,
          title: post.title,
          slug: post.slug,
          excerpt: post.excerpt,
          content: post.content,
          coverImage: post.coverImage,
          category: post.category,
          readTimeMinutes: post.readTimeMinutes,
          authorName: post.authorName,
          tags: post.tags,
          isPublished: true,
          viewsCount: post.viewsCount
        }
      });
      console.log(`Created post: ${post.title}`);
    }
  }

  console.log('✅ All blog articles seeded successfully!');
}

main()
  .catch((e) => {
    console.error('❌ Blog seeding failed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
